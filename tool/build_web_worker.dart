/// Author: Zakaria Hossain
/// Description: Build script compiling web_worker.dart to JavaScript and embedding in Dart.
library;

import 'dart:convert';
import 'dart:io';

import 'source_hash.dart';

Future<void> main() async {
  final packageRoot = Directory.current.path;
  final tempDir = await Directory.systemTemp.createTemp('flutter_phonetics_');
  try {
    final outputPath = '${tempDir.path}/worker.js';
    final result = await Process.run(Platform.resolvedExecutable, [
      'compile',
      'js',
      '-O2',
      '--no-source-maps',
      '-o',
      outputPath,
      'tool/web_worker.dart',
    ]);
    if (result.exitCode != 0) {
      stderr
        ..writeln(result.stdout)
        ..writeln(result.stderr);
      exit(result.exitCode);
    }

    final script = File(outputPath).readAsStringSync();
    final scriptLiteral = jsonEncode(script).replaceAll(r'$', r'\$');
    final hash = hashWorkerSources(packageRoot);
    File('lib/src/worker/web_worker_script.g.dart').writeAsStringSync('''
/// Author: Zakaria Hossain
/// Description: Pre-compiled web worker JavaScript script bundled as a Dart literal.
library;

// GENERATED by tool/build_web_worker.dart. Do not edit by hand.
// ignore_for_file: lines_longer_than_80_chars

const String workerSourceHash = '$hash';

const String webWorkerScript = $scriptLiteral;
''');
    stdout.writeln(
        'Wrote lib/src/worker/web_worker_script.g.dart (${(script.length / 1024).toStringAsFixed(1)} KB, hash $hash)');
  } finally {
    await tempDir.delete(recursive: true);
  }
}
